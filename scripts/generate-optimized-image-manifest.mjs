import { mkdir, readFile, writeFile } from 'node:fs/promises'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const __filename = fileURLToPath(import.meta.url)
const __dirname = path.dirname(__filename)
const PROJECT_ROOT = path.resolve(__dirname, '..')
const SOURCE_PATH = path.join(PROJECT_ROOT, 'public', 'images', 'optimized', 'manifest.json')
const OUTPUT_PATH = path.join(PROJECT_ROOT, 'generated', 'optimized-image-manifest.ts')

function canonicalSource(value) {
  return String(value || '').trim().replace(/^http:\/\//i, 'https://').split('#')[0].split('?')[0]
}

function toPublicBasePath(baseRelativePath) {
  const clean = String(baseRelativePath || '').replace(/\\/g, '/').replace(/^\/+/, '')
  return clean ? `/images/optimized/${clean}` : ''
}

async function loadManifest() {
  try {
    return JSON.parse(await readFile(SOURCE_PATH, 'utf8'))
  } catch {
    return {}
  }
}

const rawManifest = await loadManifest()
const compact = {}

for (const [rawSource, rawEntry] of Object.entries(rawManifest)) {
  if (!rawEntry || rawEntry.done !== true || !rawEntry.baseRelativePath) continue

  const source = canonicalSource(rawSource)
  if (!source) continue

  const widths = Array.isArray(rawEntry.widths)
    ? [...new Set(rawEntry.widths.map(Number).filter((value) => Number.isFinite(value) && value > 0))].sort((a, b) => a - b)
    : []

  const base = toPublicBasePath(rawEntry.baseRelativePath)
  if (!base || !widths.length) continue

  compact[source] = { base, widths }
}

await mkdir(path.dirname(OUTPUT_PATH), { recursive: true })
await writeFile(
  OUTPUT_PATH,
  `// AUTO-GENERATED by scripts/generate-optimized-image-manifest.mjs\n` +
  `// Do not edit manually. If public/images/optimized/manifest.json is absent, this map is empty.\n` +
  `export const optimizedImageManifest = ${JSON.stringify(compact, null, 2)} as const\n\n` +
  `export type OptimizedImageManifest = typeof optimizedImageManifest\n`,
  'utf8',
)

console.log(`Optimized image manifest: ${Object.keys(compact).length} entries`)
