import { promises as fs } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const rootDir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const articlesDir = path.join(rootDir, 'content', 'articles-json')
const outputFile = path.join(articlesDir, 'articles.cards.ts')

const stripHtml = (value = '') => String(value)
  .replace(/<script[\s\S]*?<\/script>/gi, ' ')
  .replace(/<style[\s\S]*?<\/style>/gi, ' ')
  .replace(/<[^>]+>/g, ' ')
  .replace(/&nbsp;/gi, ' ')
  .replace(/&amp;/gi, '&')
  .replace(/&quot;/gi, '"')
  .replace(/&#39;|&apos;/gi, "'")
  .replace(/&laquo;/gi, '«')
  .replace(/&raquo;/gi, '»')
  .replace(/\s+/g, ' ')
  .trim()

const truncate = (value, max = 220) => {
  const text = stripHtml(value)
  if (text.length <= max) return text
  const cut = text.slice(0, max + 1)
  const lastSpace = cut.lastIndexOf(' ')
  return `${cut.slice(0, lastSpace > max * 0.7 ? lastSpace : max).trim()}…`
}

const entries = await fs.readdir(articlesDir, { withFileTypes: true })
const jsonFiles = entries
  .filter((entry) => entry.isFile() && entry.name.endsWith('.json'))
  .map((entry) => entry.name)
  .sort()

const cards = []
let missingDescriptionCount = 0
for (const fileName of jsonFiles) {
  const raw = await fs.readFile(path.join(articlesDir, fileName), 'utf8')
  const article = JSON.parse(raw)
  const slug = String(article.slug || fileName.replace(/\.json$/, ''))
  if (!slug || !article.title) {
    throw new Error(`[articles] ${fileName}: slug/title are required`)
  }
  if (!String(article.description || '').trim()) missingDescriptionCount += 1

  cards.push({
    id: article.id,
    slug,
    title: article.title,
    preview: truncate(article.preview || article.description || article.contentTop || ''),
    image: article.image || article.cover || '',
    date: article.date || '',
    time: article.time || 0,
    views: article.views || 0,
    comments: article.comments || 0,
    properties: article.properties || {},
  })
}

cards.sort((a, b) => String(b.date).localeCompare(String(a.date)))

const output = `/* auto-generated by scripts/generate-articles-cards.mjs */\nexport const ARTICLE_CARDS: any[] = ${JSON.stringify(cards, null, 2)}\n`
await fs.writeFile(outputFile, output, 'utf8')
console.log(`[articles] generated ${cards.length} cards -> ${path.relative(rootDir, outputFile)}`)
console.log(`[articles] ${missingDescriptionCount} articles use automatic SEO-description fallback`)
