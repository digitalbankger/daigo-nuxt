import { defineStore } from 'pinia'
import { ref } from 'vue'

/**
 * Тип для пользователя. Хранит минимальный набор полей, необходимых
 * для регистрации неавторизованного пользователя. В случае авторизации
 * бэкенд может возвращать расширенный объект пользователя.
 */
export interface User {
  id: number | null
  fullName: string
  phone: string
  city: string
}

/**
 * Хранилище авторизации. Отвечает за информацию о текущем пользователе
 * и флаг авторизации. Хранилище изолировано от корзины, чтобы его можно
 * было использовать во всём приложении. В дальнейшем при подключении
 * настоящего API здесь можно будет организовать загрузку профиля,
 * обработку токенов и т.д.
 */
export const useAuthStore = defineStore('auth', () => {
  // Флаг авторизации. По умолчанию пользователь не авторизован.
  const isAuthenticated = ref(false)
  // Данные пользователя. При успешной регистрации или авторизации
  // здесь будет лежать объект пользователя. Пока null.
  const user = ref<User | null>(null)

  /**
   * Устанавливает данные пользователя и отмечает его как авторизованного.
   * Вызывается после успешной регистрации или логина.
   */
  function setUser(u: User) {
    user.value = u
    isAuthenticated.value = true
  }

  /**
   * Сбрасывает данные пользователя и флаг авторизации. Используется
   * при выходе из системы.
   */
  function clearUser() {
    user.value = null
    isAuthenticated.value = false
  }

  return {
    isAuthenticated,
    user,
    setUser,
    clearUser,
  }
})